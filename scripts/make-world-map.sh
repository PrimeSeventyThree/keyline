#!/usr/bin/env bash
# Builds the dotted world map behind the Connect screen from Natural Earth's 1:110m
# countries (public domain, https://www.naturalearthdata.com) into
# App/Assets.xcassets/WorldMap.imageset/world-map.svg: land as dots, a vector template image.
#
# The map is equirectangular from 180°W to 180°E and from 84°N to 58°S (Antarctica left
# out).
#
# Usage: scripts/make-world-map.sh
set -euo pipefail

repo_root="$(cd "$(dirname "$0")/.." && pwd)"
source_url="https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_admin_0_countries.geojson"
step=2          # degrees between dots
north=84
south=-58
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

curl -sSfL -o "$work/countries.geojson" "$source_url"

# Every polygon ring as edges "lon1 lat1 lon2 lat2", for an even-odd point-in-polygon test.
jq -r '
  .features[].geometry
  | (if .type == "Polygon" then [.coordinates] else .coordinates end)[][]
  | . as $ring | range(0; length - 1) | "\($ring[.][0]) \($ring[.][1]) \($ring[. + 1][0]) \($ring[. + 1][1])"
' "$work/countries.geojson" > "$work/edges.txt"

width=$(( 360 / step ))
height=$(( (north - south) / step ))

# Dots at cell centres, kept when a ray from the point crosses the land edges an odd number of
# times. Edges are bucketed by row so each point only checks edges spanning its latitude.
awk -v step="$step" -v north="$north" -v width="$width" -v height="$height" '
  { x1[NR] = $1; y1[NR] = $2; x2[NR] = $3; y2[NR] = $4
    lo = ($2 < $4 ? $2 : $4); hi = ($2 < $4 ? $4 : $2)
    for (r = 0; r < height; r++) {
      lat = north - (r + 0.5) * step
      if (lat >= lo && lat < hi) rows[r] = rows[r] " " NR
    }
  }
  END {
    printf "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 %d %d\" width=\"%d\" height=\"%d\">\n", width * 10, height * 10, width * 10, height * 10
    printf "  <title>Keyline world map</title>\n"
    printf "  <!-- Land from Natural Earth 1:110m countries (public domain), one dot every %d°. Generated by scripts/make-world-map.sh. -->\n", step
    printf "  <g id=\"land\" fill=\"currentColor\">\n"
    dots = 0
    for (r = 0; r < height; r++) {
      lat = north - (r + 0.5) * step
      n = split(rows[r], ids, " ")
      for (c = 0; c < width; c++) {
        lon = -180 + (c + 0.5) * step
        inside = 0
        for (k = 1; k <= n; k++) {
          e = ids[k]
          if ((y1[e] > lat) != (y2[e] > lat)) {
            cross = x1[e] + (lat - y1[e]) * (x2[e] - x1[e]) / (y2[e] - y1[e])
            if (lon < cross) inside = !inside
          }
        }
        if (inside) { printf "    <circle cx=\"%d\" cy=\"%d\" r=\"3\"/>\n", c * 10 + 5, r * 10 + 5; dots++ }
      }
    }
    printf "  </g>\n</svg>\n"
    print dots " dots" > "/dev/stderr"
  }
' "$work/edges.txt" > "$work/world-map.svg"

image_set="$repo_root/App/Assets.xcassets/WorldMap.imageset"
mkdir -p "$image_set"
cp "$work/world-map.svg" "$image_set/world-map.svg"
cat > "$image_set/Contents.json" <<EOF
{
  "images" : [ { "filename" : "world-map.svg", "idiom" : "universal" } ],
  "info" : { "author" : "xcode", "version" : 1 },
  "properties" : {
    "preserves-vector-representation" : true,
    "template-rendering-intent" : "template"
  }
}
EOF

